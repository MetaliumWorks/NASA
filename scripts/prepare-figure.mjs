// Prepares the figure artwork from the two public-domain drawings in assets-source/.
// Node port of docs/mockups/build_v4.py; it uses the same element ids.
//
//   npm run prepare-figure
//
// - Skeleton: the right arm (drawn palm-backward, forearm bones crossed) is replaced by
//   a mirror of the left arm, so both arms are in the same position. Editor metadata is
//   stripped. Output: src/figure/generated/skeleton.ts
// - Organs: the embedded images are pulled out of the organ drawing as files, each in
//   the format it was embedded in. Output: src/figure/generated/organs/
//
// The output is committed, so the app builds without running this script.
import { DOMParser, XMLSerializer } from '@xmldom/xmldom';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

const SKELETON_SRC = 'assets-source/Human_skeleton_front_-_no_labels.svg';
const ORGANS_SRC = 'assets-source/Man_shadow_anatomy_expanded_and_with_DVT.svg';
const OUT = 'src/figure/generated';

const DROP_PREFIXES = ['sodipodi:', 'inkscape:', 'xml:'];
const REMOVE = ['HumerusRight', 'UlnaRight', 'RadiusRight', 'HandRight', 'g1753'];
const MIRROR = ['HumerusLeft', 'RadiusLeft', 'UlnaLeft', 'HandLeft', 'path1679', 'path1681', 'path1683'];

// id in the organ drawing -> file name without extension
const ORGAN_FILES = {
  'image2204-9': 'brain',
  image7849: 'lungs',
  image3855: 'heart',
  image10296: 'liver',
  image3706: 'stomach',
  'image2224-4': 'intestines',
  image6280: 'kidneys',
  // Blood & immunity
  'image2218-4': 'lymph-neck',
  'image2339-8': 'lymph-axilla',
  'image2395-5-7': 'spleen',
  // Muscles. The drawing has one thigh and one lower leg; the other side is its mirror (layout.ts).
  image3428: 'thigh',
  image3399: 'leg',
};

const fail = (message) => {
  console.error(message);
  process.exit(1);
};
const parse = (path) => new DOMParser().parseFromString(readFileSync(path, 'utf8'), 'image/svg+xml');
const elements = (node) => Array.from(node.childNodes ?? []).filter((n) => n.nodeType === 1);

function walk(el, visit) {
  visit(el);
  for (const child of elements(el)) walk(child, visit);
}

// ---------------------------------------------------------------- skeleton
const skeleton = parse(SKELETON_SRC);

/** Drop editor attributes and the whitespace between elements. */
function clean(el) {
  walk(el, (node) => {
    for (const attr of Array.from(node.attributes)) {
      if (DROP_PREFIXES.some((p) => attr.name.startsWith(p))) node.removeAttributeNode(attr);
    }
    for (const child of Array.from(node.childNodes)) {
      if (child.nodeType === 3 && child.data.trim() === '') node.removeChild(child);
      if (child.nodeType === 8) node.removeChild(child);
    }
  });
}

const gradients = [];
let layer = null;
walk(skeleton.documentElement, (el) => {
  if (el.localName === 'linearGradient' || el.localName === 'radialGradient') gradients.push(el);
  if (el.getAttribute('id') === 'layer3') layer = el;
});
if (!layer) fail('skeleton layer "layer3" not found');
for (const el of [...gradients, layer]) clean(el);

const byId = new Map(elements(layer).map((el) => [el.getAttribute('id'), el]));
const missing = [...REMOVE, ...MIRROR].filter((id) => !byId.has(id));
if (missing.length) fail('skeleton ids not found: ' + missing.join(', '));

for (const id of REMOVE) layer.removeChild(byId.get(id));
const arm = skeleton.createElementNS('http://www.w3.org/2000/svg', 'g');
arm.setAttribute('id', 'ArmRightMirrored');
arm.setAttribute('transform', 'translate(406 0) scale(-1 1)');
for (const id of MIRROR) {
  const copy = byId.get(id).cloneNode(true);
  walk(copy, (el) => {
    if (el.getAttribute('id')) el.setAttribute('id', el.getAttribute('id') + '-m');
  });
  arm.appendChild(copy);
}
layer.appendChild(arm);

const serializer = new XMLSerializer();
const serialize = (el) => serializer.serializeToString(el).replace(/ xmlns(:\w+)?="[^"]*"/g, '');
const defs = gradients.map(serialize).join('');
const markup = serialize(layer);
for (const [name, text] of [['defs', defs], ['markup', markup]]) {
  if (/sodipodi:|inkscape:|xml:space/.test(text)) fail(`editor metadata left in skeleton ${name}`);
  if (text.includes('`') || text.includes('${')) fail(`skeleton ${name} cannot be written as a template literal`);
}

mkdirSync(`${OUT}/organs`, { recursive: true });
writeFileSync(
  `${OUT}/skeleton.ts`,
  [
    '// Generated by scripts/prepare-figure.mjs from assets-source/. Do not edit by hand.',
    '// Skeleton drawing by Mariana Ruiz Villarreal, unlabelled edition by Mikael Häggström. Public domain, via Wikimedia Commons.',
    '/* eslint-disable */',
    '',
    `export const SKELETON_DEFS: string = \`${defs}\`;`,
    '',
    `export const SKELETON_MARKUP: string = \`${markup}\`;`,
    '',
  ].join('\n'),
);

// ---------------------------------------------------------------- organs
const organs = parse(ORGANS_SRC);
const images = new Map();
walk(organs.documentElement, (el) => {
  if (el.localName === 'image') images.set(el.getAttribute('id'), el);
});

for (const old of readdirSync(`${OUT}/organs`)) rmSync(`${OUT}/organs/${old}`);
const written = [];
for (const [id, name] of Object.entries(ORGAN_FILES)) {
  const image = images.get(id);
  if (!image) fail('organ image not found: ' + id);
  const href = image.getAttribute('xlink:href') || image.getAttribute('href') || '';
  const match = /^data:image\/(png|gif);base64,(.*)$/s.exec(href);
  if (!match) fail('organ image is not an embedded PNG or GIF: ' + id);
  const file = `${name}.${match[1]}`;
  const bytes = Buffer.from(match[2], 'base64');
  writeFileSync(`${OUT}/organs/${file}`, bytes);
  written.push(`${file} (${Math.round(bytes.length / 1024)} KB)`);
}

console.log(`skeleton.ts ${Math.round((defs.length + markup.length) / 1024)} KB`);
console.log('organs: ' + written.join(', '));
